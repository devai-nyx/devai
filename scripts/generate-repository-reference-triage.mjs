#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const args = process.argv.slice(2);
let rootArgument = '.';
let targetRelative;
let check = false;
for (let index = 0; index < args.length; index++) {
  const argument = args[index];
  if (argument === '--check') {
    check = true;
    continue;
  }
  if (argument === '--target') {
    targetRelative = args[index + 1];
    if (targetRelative === undefined || targetRelative.startsWith('--')) {
      throw new Error('--target requires a repository-relative path');
    }
    index++;
    continue;
  }
  if (argument?.startsWith('--')) throw new Error(`unknown option: ${argument}`);
  if (rootArgument !== '.') throw new Error(`unexpected positional argument: ${argument}`);
  rootArgument = argument ?? '.';
}
if (targetRelative === undefined) {
  throw new Error('--target is required; no closed-round output path is implicit');
}
if (targetRelative.startsWith('/') || targetRelative.split('/').includes('..')) {
  throw new Error('--target must stay within the repository');
}

const root = resolve(rootArgument);
const successorReference = ['devai-nyx', 'devai'].join('/');
const referencePattern = new RegExp(`${successorReference}(?:-original)?`, 'g');
const actionRegistryPath = join(root, 'law/policy/action-registry.json');
const actionRegistry = JSON.parse(readFileSync(actionRegistryPath, 'utf8'));
const actionGeneratedViews = new Set(actionRegistry.generated_views ?? []);
const actionDispositions = new Set(
  (actionRegistry.entries ?? []).map((entry) => entry.disposition),
);
if (
  actionDispositions.size !== 3 ||
  !['keep', 'fold', 'tombstone'].every((value) => actionDispositions.has(value))
) {
  throw new Error('action registry disposition semantics are incomplete');
}

export function compareUtf8Bytes(left, right) {
  return Buffer.compare(Buffer.from(left), Buffer.from(right));
}

const DISPOSITION_RULES = [
  {
    id: 'frozen-predecessor',
    classification: 'frozen-predecessor',
    action: 'retain',
    rationale:
      'Frozen predecessor identity; retained as an immutable historical or genesis binding.',
    matches: ({ matched }) => matched.endsWith('-original'),
  },
  {
    id: 'package-metadata',
    classification: 'package-metadata',
    action: 'retain',
    rationale: 'Package and repository metadata remains bound to the active successor identity.',
    matches: ({ file }) =>
      file.endsWith('package.json') ||
      file.endsWith('pnpm-lock.yaml') ||
      file.endsWith('package-lock.json'),
  },
  {
    id: 'historical-label',
    classification: 'historical-label',
    action: 'retain',
    rationale:
      'Immutable historical text records the repository name used when that evidence was created.',
    matches: ({ file }) =>
      file.includes('/predecessor/') ||
      file.startsWith('work/audit/R-0001/') ||
      file.startsWith('work/rounds/R-0001/'),
  },
  {
    id: 'generated-output',
    classification: 'generated-output',
    action: 'regenerate',
    rationale:
      'Generated bytes are recreated from their governed source instead of edited in place.',
    matches: ({ file }) =>
      actionGeneratedViews.has(file) ||
      file.startsWith('.devai/config/') ||
      file.includes('/fixtures/') ||
      file.startsWith('docs/site/'),
  },
  {
    id: 'active-successor',
    classification: 'active-successor',
    action: 'retain',
    rationale: 'Live successor reference; the active repository keeps the devai identity.',
    matches: ({ matched }) => matched === successorReference,
  },
];

export function disposition(file, matched) {
  const rule = DISPOSITION_RULES.find((candidate) => candidate.matches({ file, matched }));
  if (rule === undefined) {
    throw new Error(`repository reference has no reachable disposition: ${file}:${matched}`);
  }
  return {
    classification: rule.classification,
    action: rule.action,
    rationale: rule.rationale,
  };
}

const fixtures = JSON.parse(
  readFileSync(join(root, 'scripts/fixtures/repository-reference-dispositions.json'), 'utf8'),
);
for (const fixture of fixtures) {
  const actual = disposition(fixture.file, fixture.matched);
  if (
    actual.classification !== fixture.classification ||
    actual.action !== fixture.action
  ) {
    throw new Error(`repository reference fixture failed: ${fixture.id}`);
  }
}
const supportedActions = new Set(DISPOSITION_RULES.map((rule) => rule.action));
const fixtureActions = new Set(fixtures.map((fixture) => fixture.action));
if (
  supportedActions.size !== fixtureActions.size ||
  [...supportedActions].some((action) => !fixtureActions.has(action))
) {
  throw new Error('every supported repository-reference action requires a fixture');
}

const files = execFileSync('git', ['ls-files', '-z'], { cwd: root })
  .toString('utf8')
  .split('\0')
  .filter((file) => file.length > 0 && file !== targetRelative)
  .sort(compareUtf8Bytes);
const references = [];
for (const file of files) {
  let content;
  try {
    content = readFileSync(join(root, file), 'utf8');
  } catch {
    continue;
  }
  for (const [lineIndex, line] of content.split('\n').entries()) {
    referencePattern.lastIndex = 0;
    for (const match of line.matchAll(referencePattern)) {
      references.push({
        locator: `${file}:${String(lineIndex + 1)}:${String((match.index ?? 0) + 1)}:${match[0]}`,
        ...disposition(file, match[0]),
      });
    }
  }
}
references.sort((left, right) => compareUtf8Bytes(left.locator, right.locator));
const bytes = `${JSON.stringify({ schemaVersion: '1.0.0', references }, null, 2)}\n`;
const target = join(root, targetRelative);
if (check) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== bytes) {
    process.stderr.write(`repository reference projection is stale: ${targetRelative}\n`);
    process.exitCode = 1;
  } else {
    process.stdout.write(`${String(references.length)} repository references verified\n`);
  }
} else {
  writeFileSync(target, bytes);
  process.stdout.write(`${String(references.length)} repository references classified\n`);
}
